#include<bits/stdc++.h>
using namespace std;
int main() { 
    int x = 29, y = 10;

    cout<<x+y<<endl;
    cout<<x-y<<endl;
    cout<<x*y<<endl;
    cout<<x/y<<endl;
    cout<<x%y<<endl;

    x = 5;
    cout<<x++<<endl;;
    cout<<x<<endl;
    cout<<x--<<endl;
    cout<<x<<endl;

    cout<<++x<<endl;
    cout<<x<<endl;
    cout<<--x<<endl;
    cout<<x;

    return 0;
}