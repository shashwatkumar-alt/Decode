// How much space does following data types take?

// 1. int = 4 bytes
// 2. bool = 1 bytes
// 3. float = 4 bytes

#include<bits/stdc++.h>
using namespace std;
int main() { 
    cout<<"Size of int is "<<sizeof(int)<<endl;
    cout<<"Size of bool is "<<sizeof(bool)<<endl;
    cout<<"Size of float is "<<sizeof(float)<<endl;
    return 0;
}